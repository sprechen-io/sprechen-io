using System.Text;
using System.Text.Json;

namespace Sprechen.Forms.TypeScriptCodegen;

/// <summary>
/// Projiziert die kanonischen Telemetrie-JSON-Schema-Dokumente in die klassische TypeScript-Laufzeit.
/// Der Browser-Prüfer liest diese Dokumente direkt. Nutzlastformen und Vokabulare bleiben bei den MDA-Schemata.
/// </summary>
public static class TelemetryCheckpointSchemaGenerator
{
    public const string OutputRelativePath =
        "src/forms/Sprechen.Forms/TypeScript/Generated/telemetryCheckpointSchemas.generated.ts";

    private static readonly string[] SchemaRelativePaths =
    [
        "src/model/evaluationsmodell/schemas/telemetry-events.schema.json",
        "src/model/evaluationsmodell/schemas/telemetry-fragments.schema.json",
    ];

    private static readonly HashSet<string> SupportedSchemaKeywords =
    [
        "$schema",
        "$id",
        "$defs",
        "$ref",
        "title",
        "description",
        "allOf",
        "anyOf",
        "oneOf",
        "not",
        "const",
        "enum",
        "type",
        "minLength",
        "maxLength",
        "pattern",
        "format",
        "minimum",
        "maximum",
        "minItems",
        "maxItems",
        "items",
        "required",
        "properties",
        "additionalProperties",
        "unevaluatedProperties",
        "if",
        "then",
        "else",
    ];

    private static readonly HashSet<string> SupportedTypes =
    [
        "null",
        "boolean",
        "string",
        "number",
        "integer",
        "array",
        "object",
    ];

    public static string GenerateText(string repositoryRoot)
    {
        var documents = new List<(string Id, string Json)>();
        foreach (var relativePath in SchemaRelativePaths)
        {
            var absolutePath = Path.Combine(repositoryRoot, relativePath);
            using var document = JsonDocument.Parse(File.ReadAllText(absolutePath));
            EnsureOnlySupportedKeywords(document.RootElement, relativePath);
            var id = document.RootElement.GetProperty("$id").GetString()
                ?? throw new InvalidOperationException($"Telemetry schema '{relativePath}' has no $id.");
            documents.Add((id, JsonSerializer.Serialize(document.RootElement)));
        }

        var builder = new StringBuilder();
        builder.Append("// <auto-generated>\n");
        builder.Append("// Aus den Telemetrie-JSON-Schemata erzeugt; Änderungen an den Schemata vornehmen.\n");
        builder.Append("// Neu erzeugen: dotnet run --project src/forms/Sprechen.Forms.TypeScriptCodegen -- --repo-root <repo-root>\n");
        builder.Append("// </auto-generated>\n\n");
        builder.Append("var telemetryCheckpointRootSchemaId = ");
        builder.Append(JsonSerializer.Serialize(documents[0].Id));
        builder.Append(";\n\n");
        builder.Append("var telemetryCheckpointSchemaDocuments: Record<string, unknown> = {\n");
        foreach (var (id, json) in documents)
        {
            builder.Append("    ");
            builder.Append(JsonSerializer.Serialize(id));
            builder.Append(": ");
            builder.Append(json);
            builder.Append(",\n");
        }
        builder.Append("};\n");
        return builder.ToString();
    }

    /// <summary>
    /// Prüft die Schemadokumente gegen die unterstützten Schlüsselwörter und Werteformen.
    /// Namen unter properties und $defs werden als Datenschlüssel behandelt.
    /// </summary>
    public static void EnsureOnlySupportedKeywords(JsonElement schema, string sourceName)
        => EnsureOnlySupportedKeywords(schema, sourceName, "#");

    private static void EnsureOnlySupportedKeywords(
        JsonElement schema,
        string sourceName,
        string pointer)
    {
        if (schema.ValueKind is JsonValueKind.True or JsonValueKind.False)
        {
            return;
        }
        if (schema.ValueKind != JsonValueKind.Object)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' has a non-schema value at '{pointer}'.");
        }

        foreach (var property in schema.EnumerateObject())
        {
            if (!SupportedSchemaKeywords.Contains(property.Name))
            {
                throw new InvalidOperationException(
                    $"Telemetry schema '{sourceName}' uses unsupported keyword " +
                    $"'{property.Name}' at '{pointer}'.");
            }

            var childPointer = $"{pointer}/{EscapePointerSegment(property.Name)}";
            switch (property.Name)
            {
                case "$schema":
                case "$id":
                case "$ref":
                case "title":
                case "description":
                case "pattern":
                    EnsureString(property.Value, sourceName, childPointer);
                    if (property.Name == "pattern")
                    {
                        EnsureValidPattern(property.Value.GetString()!, sourceName, childPointer);
                    }
                    break;
                case "$defs":
                case "properties":
                    EnsureSchemaMap(property.Value, sourceName, childPointer);
                    break;
                case "allOf":
                case "anyOf":
                case "oneOf":
                    EnsureSchemaArray(property.Value, sourceName, childPointer);
                    break;
                case "not":
                case "items":
                case "if":
                case "then":
                case "else":
                    EnsureOnlySupportedKeywords(property.Value, sourceName, childPointer);
                    break;
                case "additionalProperties" when property.Value.ValueKind != JsonValueKind.True
                    && property.Value.ValueKind != JsonValueKind.False:
                    EnsureOnlySupportedKeywords(property.Value, sourceName, childPointer);
                    break;
                case "unevaluatedProperties" when property.Value.ValueKind != JsonValueKind.True
                    && property.Value.ValueKind != JsonValueKind.False:
                    EnsureOnlySupportedKeywords(property.Value, sourceName, childPointer);
                    break;
                case "format":
                    if (property.Value.ValueKind != JsonValueKind.String
                        || property.Value.GetString() != "date-time")
                    {
                        throw new InvalidOperationException(
                            $"Telemetry schema '{sourceName}' uses unsupported format " +
                            $"'{property.Value}' at '{childPointer}'.");
                    }
                    break;
                case "type":
                    EnsureSupportedTypes(property.Value, sourceName, childPointer);
                    break;
                case "enum":
                    EnsureNonEmptyUniqueArray(property.Value, sourceName, childPointer);
                    break;
                case "required":
                    EnsureUniqueStringArray(property.Value, sourceName, childPointer);
                    break;
                case "minLength":
                case "maxLength":
                case "minItems":
                case "maxItems":
                    EnsureNonNegativeInteger(property.Value, sourceName, childPointer);
                    break;
                case "minimum":
                case "maximum":
                    EnsureNumber(property.Value, sourceName, childPointer);
                    break;
            }
        }
    }

    private static void EnsureSchemaMap(JsonElement value, string sourceName, string pointer)
    {
        if (value.ValueKind != JsonValueKind.Object)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires a schema map at '{pointer}'.");
        }
        foreach (var property in value.EnumerateObject())
        {
            EnsureOnlySupportedKeywords(
                property.Value,
                sourceName,
                $"{pointer}/{EscapePointerSegment(property.Name)}");
        }
    }

    private static void EnsureSchemaArray(JsonElement value, string sourceName, string pointer)
    {
        if (value.ValueKind != JsonValueKind.Array || value.GetArrayLength() == 0)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires a schema array at '{pointer}'.");
        }
        var index = 0;
        foreach (var item in value.EnumerateArray())
        {
            EnsureOnlySupportedKeywords(item, sourceName, $"{pointer}/{index}");
            index++;
        }
    }

    private static void EnsureSupportedTypes(JsonElement value, string sourceName, string pointer)
    {
        var types = value.ValueKind == JsonValueKind.Array
            ? value.EnumerateArray().ToArray()
            : [value];
        if (types.Length == 0)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires at least one type at '{pointer}'.");
        }
        var uniqueTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var type in types)
        {
            if (type.ValueKind != JsonValueKind.String
                || !SupportedTypes.Contains(type.GetString()!)
                || !uniqueTypes.Add(type.GetString()!))
            {
                throw new InvalidOperationException(
                    $"Telemetry schema '{sourceName}' uses unsupported type " +
                    $"'{type}' at '{pointer}'.");
            }
        }
    }

    private static void EnsureString(JsonElement value, string sourceName, string pointer)
    {
        if (value.ValueKind != JsonValueKind.String)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires a string at '{pointer}'.");
        }
    }

    private static void EnsureValidPattern(string value, string sourceName, string pointer)
    {
        try
        {
            _ = new System.Text.RegularExpressions.Regex(value);
        }
        catch (ArgumentException exception)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' has an invalid pattern at '{pointer}'.", exception);
        }
    }

    private static void EnsureNonEmptyUniqueArray(JsonElement value, string sourceName, string pointer)
    {
        if (value.ValueKind != JsonValueKind.Array || value.GetArrayLength() == 0)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires a non-empty array at '{pointer}'.");
        }
        var entries = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in value.EnumerateArray())
        {
            if (!entries.Add(item.GetRawText()))
            {
                throw new InvalidOperationException(
                    $"Telemetry schema '{sourceName}' requires unique values at '{pointer}'.");
            }
        }
    }

    private static void EnsureUniqueStringArray(JsonElement value, string sourceName, string pointer)
    {
        if (value.ValueKind != JsonValueKind.Array)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires a string array at '{pointer}'.");
        }
        var entries = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in value.EnumerateArray())
        {
            if (item.ValueKind != JsonValueKind.String || !entries.Add(item.GetString()!))
            {
                throw new InvalidOperationException(
                    $"Telemetry schema '{sourceName}' requires unique strings at '{pointer}'.");
            }
        }
    }

    private static void EnsureNonNegativeInteger(JsonElement value, string sourceName, string pointer)
    {
        if (value.ValueKind != JsonValueKind.Number || !value.TryGetInt64(out var number) || number < 0)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires a non-negative integer at '{pointer}'.");
        }
    }

    private static void EnsureNumber(JsonElement value, string sourceName, string pointer)
    {
        if (value.ValueKind != JsonValueKind.Number)
        {
            throw new InvalidOperationException(
                $"Telemetry schema '{sourceName}' requires a number at '{pointer}'.");
        }
    }

    private static string EscapePointerSegment(string value)
        => value.Replace("~", "~0", StringComparison.Ordinal)
            .Replace("/", "~1", StringComparison.Ordinal);
}
