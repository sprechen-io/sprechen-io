using System.Text;
using Sprechen.Mda.Contracts.V1.Catalog;

namespace Sprechen.Forms.TypeScriptCodegen;

/// <summary>
/// Erzeugt die TypeScript-Typen und lokalisierten Navigationstexte aus dem Textkatalog.
/// Die Sprachreihenfolge des Katalogs bestimmt Ersatzsprache und Präfixreihenfolge.
/// </summary>
public static class FormsNavigationTextMapGenerator
{
    public const string OutputRelativePath = "src/forms/Sprechen.Forms/TypeScript/Generated/formNavigationTextMap.generated.ts";

    // Benötigte Textschlüssel in Ausgabereihenfolge. Fehlt ein Schlüssel
    // oder seine Übersetzung im Katalog, wird die Erzeugung abgebrochen.
    private static readonly (string CopyId, string TsKey)[] EmittedKeys =
    [
        ("CancelConfirm", "cancelConfirm"),
        ("CancelTitle", "cancelTitle"),
        ("CancelledText", "cancelledText"),
        ("DemonstrationRestartAfterCancelText", "demonstrationRestartAfterCancelText"),
        ("DemonstrationRestartAfterSubmitText", "demonstrationRestartAfterSubmitText"),
        ("PagerNavLabel", "pagerNavLabel"),
        ("PagerNext", "pagerNext"),
        ("PagerNextGroupTemplate", "pagerNextGroupTemplate"),
        ("PagerPrevious", "pagerPrevious"),
        ("PagerPreviousGroupTemplate", "pagerPreviousGroupTemplate"),
        ("PagerStepTemplate", "pagerStepTemplate"),
        ("PrerequisitesTitle", "prerequisitesTitle"),
        ("RestartLabel", "restartLabel"),
        ("SelectionLink", "selectionLink"),
        ("SharedImportPrefix", "sharedImportPrefix"),
        ("StudyRestartedText", "studyRestartedText"),
        ("SuccessNextSteps", "successNextSteps"),
        ("SuccessSubmittedText", "successSubmittedText"),
        ("SuccessTitle", "successTitle"),
        ("TelemetryConcurrentWriterErrorText", "telemetryConcurrentWriterErrorText"),
        ("TelemetryErrorTitle", "telemetryErrorTitle"),
        ("TelemetryInitializationErrorText", "telemetryInitializationErrorText"),
        ("TelemetryTerminalErrorText", "telemetryTerminalErrorText"),
        ("TelemetryTerminalVolatileErrorText", "telemetryTerminalVolatileErrorText"),
        ("TelemetryTerminalPendingText", "telemetryTerminalPendingText"),
        ("ValidationInvalidFormatFallback", "validationInvalidFormatFallback"),
        ("ValidationInvalidValueFallback", "validationInvalidValueFallback"),
        ("ValidationRequiredFallback", "validationRequiredFallback"),
        ("ValidationSummaryTitle", "validationSummaryTitle"),
    ];

    // Globale Werte werden mit var ausgegeben, damit formNavigation.js
    // als separates klassisches Skript auf sie zugreifen kann.
    public static string GenerateText()
    {
        var languages = SupportedLanguages();
        var fallback = languages[0].IsoCode;
        var prefixOrder = languages.Skip(1).Select(language => language.IsoCode).ToArray();

        var builder = new StringBuilder();
        builder.Append("// <auto-generated>\n");
        builder.Append("// Aus FormsChromeCopy erzeugt; Änderungen am Textkatalog vornehmen.\n");
        builder.Append("// Neu erzeugen: dotnet run --project src/forms/Sprechen.Forms.TypeScriptCodegen -- --repo-root <repo-root>\n");
        builder.Append("// </auto-generated>\n\n");

        builder.Append("type UiLanguage = ");
        builder.Append(string.Join(" | ", languages.Select(language => $"\"{language.IsoCode}\"")));
        builder.Append(";\n\n");

        builder.Append("type UiTextKey =\n");
        for (var index = 0; index < EmittedKeys.Length; index++)
        {
            var terminator = index == EmittedKeys.Length - 1 ? ";" : "";
            builder.Append($"    | \"{EmittedKeys[index].TsKey}\"{terminator}\n");
        }

        builder.Append('\n');
        builder.Append($"var formNavigationUiLanguageFallback: UiLanguage = \"{fallback}\";\n\n");
        builder.Append("var formNavigationUiLanguagePrefixOrder: readonly UiLanguage[] = [");
        builder.Append(string.Join(", ", prefixOrder.Select(isoCode => $"\"{isoCode}\"")));
        builder.Append("];\n\n");

        builder.Append("var formNavigationUiTextMap: Record<UiLanguage, Record<UiTextKey, string>> = {\n");
        for (var languageIndex = 0; languageIndex < languages.Length; languageIndex++)
        {
            var language = languages[languageIndex];
            builder.Append($"    {language.IsoCode}: {{\n");
            for (var keyIndex = 0; keyIndex < EmittedKeys.Length; keyIndex++)
            {
                var key = EmittedKeys[keyIndex];
                var text = ResolveText(key.CopyId, language.PropertyName);
                builder.Append($"        {key.TsKey}: \"{Escape(text)}\",\n");
            }

            var languageTerminator = languageIndex == languages.Length - 1 ? "}" : "},";
            builder.Append($"    {languageTerminator}\n");
        }

        builder.Append("};\n");
        return builder.ToString();
    }



    private static (string IsoCode, string PropertyName)[] SupportedLanguages()
        => FormsChromeCopyLoader.Catalog.SupportedLanguages
            .Select(isoCode => (isoCode, isoCode))
            .ToArray();

    private static string ResolveText(string copyId, string languagePropertyName)
    {
        var entry = FormsChromeCopyLoader.Catalog.Entries
            .FirstOrDefault(candidate => string.Equals(candidate.Id, copyId, StringComparison.Ordinal));
        if (entry is null)
        {
            throw new InvalidOperationException($"The chrome copy catalog has no entry '{copyId}' required by the formNavigation text map.");
        }

        if (!entry.Texts.TryGetValue(languagePropertyName, out var text))
        {
            throw new InvalidOperationException($"The chrome copy catalog entry '{copyId}' has no text for language '{languagePropertyName}'.");
        }

        return text;
    }

    private static string Escape(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var character in value)
        {
            switch (character)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    builder.Append(character);
                    break;
            }
        }

        return builder.ToString();
    }
}
