using System.Text;
using Sprechen.Mda.Contracts.V1.Telemetry;

namespace Sprechen.Forms.TypeScriptCodegen;

/// <summary>
/// Erzeugt TypeScript-Typen und Laufzeitwerte aus den gemeinsamen Telemetrie-Konstanten,
/// damit die Forms-Anwendung dasselbe Vokabular verwendet.
/// </summary>
public static class TelemetryVocabularyGenerator
{
    public const string OutputRelativePath = "src/forms/Sprechen.Forms/TypeScript/Generated/telemetryVocabulary.generated.ts";

    // Die Reihenfolge dieser Liste bestimmt die Reihenfolge der ausgegebenen Typen.
    // Die Werte der Konstantenmengen werden für reproduzierbare Ausgabe ordinal sortiert.
    private static readonly (string TsTypeName, Func<IEnumerable<string>> Values)[] EmittedUnions =
    [
        ("StudyCondition", () => Enum.GetNames<StudyCondition>()),
        ("TaskEndState", () => Sorted(TelemetryTaskEndStates.All)),
        ("RecordProvenance", () => Sorted(TelemetryRecordProvenances.All)),
        ("CanonicalClass", () => Sorted(TelemetryCanonicalClasses.All)),
        ("TransitionScope", () => Sorted(TelemetryTransitionScopes.All)),
        ("ResultingState", () => Sorted(TelemetryResultingStates.All)),
        ("AmbiguityType", () => Sorted(TelemetryAmbiguityTypes.All)),
        ("AmbiguityResolutionStrategy", () => Sorted(TelemetryAmbiguityResolutionStrategies.All)),
        ("AmbiguitySignalClass", () => Sorted(TelemetryAmbiguitySignalClasses.All)),
        ("AmbiguityResult", () => Sorted(TelemetryAmbiguityResults.All)),
        ("ErrorTrigger", () => Sorted(TelemetryErrorTriggers.All)),
        ("StudyDiagnosisCode", () => Sorted(TelemetryStudyDiagnosisCodes.All)),
        ("StudyErrorRoute", () => Sorted(Enum.GetNames<TelemetryStudyErrorRoute>().Select(name => name.ToLowerInvariant()))),
        ("Severity", () => Sorted(TelemetrySeverityLevels.All)),
        ("LoggingScope", () => Sorted(TelemetryScopes.All)),
        ("ContractScope", () => Sorted(TelemetryScopeMapping.ContractToLoggingScope.Keys)),
    ];

    // Globale Werte werden mit var ausgegeben, damit andere klassische Skripte
    // wie evaluationTelemetry.js auf sie zugreifen können.
    public static string GenerateText()
    {
        var builder = new StringBuilder();
        builder.Append("// <auto-generated>\n");
        builder.Append("// Aus Sprechen.Mda.Contracts.V1.Telemetry erzeugt; Änderungen an der Quelle vornehmen.\n");
        builder.Append("// Neu erzeugen: dotnet run --project src/forms/Sprechen.Forms.TypeScriptCodegen -- --repo-root <repo-root>\n");
        builder.Append("// </auto-generated>\n\n");

        foreach (var (tsTypeName, values) in EmittedUnions)
        {
            builder.Append($"type {tsTypeName} =\n");
            var valueList = values().ToArray();
            for (var index = 0; index < valueList.Length; index++)
            {
                var terminator = index == valueList.Length - 1 ? ";" : "";
                builder.Append($"    | \"{valueList[index]}\"{terminator}\n");
            }

            builder.Append('\n');
        }

        AppendRuntimeSet(builder, "telemetryCanonicalClasses", "CanonicalClass", Sorted(TelemetryCanonicalClasses.All));
        AppendRuntimeSet(builder, "telemetryTransitionScopes", "TransitionScope", Sorted(TelemetryTransitionScopes.All));
        AppendRuntimeSet(builder, "telemetryResultingStates", "ResultingState", Sorted(TelemetryResultingStates.All));

        builder.Append("var telemetryScopeMapping: Record<ContractScope, LoggingScope> = {\n");
        var mappingPairs = TelemetryScopeMapping.ContractToLoggingScope
            .OrderBy(pair => pair.Key, StringComparer.Ordinal)
            .ToArray();
        for (var index = 0; index < mappingPairs.Length; index++)
        {
            var terminator = index == mappingPairs.Length - 1 ? "" : ",";
            builder.Append($"    {mappingPairs[index].Key}: \"{mappingPairs[index].Value}\"{terminator}\n");
        }

        // Die erzeugten Helfer akzeptieren Vertrags- und Loggingnamen unabhängig von
        // Großschreibung und äußeren Leerzeichen. Unbekannte Werte fallen auf field zurück.
        builder.Append("};\n\n");
        builder.Append("var normalizeContractScope = (scope: ContractScope | string | null | undefined): ContractScope => {\n");
        builder.Append("    const normalized = (scope ?? \"field\").trim().toLowerCase();\n");
        builder.Append("    for (const contractScope of Object.keys(telemetryScopeMapping) as ContractScope[]) {\n");
        builder.Append("        if (normalized === contractScope.toLowerCase() || normalized === telemetryScopeMapping[contractScope]) {\n");
        builder.Append("            return contractScope;\n");
        builder.Append("        }\n");
        builder.Append("    }\n\n");
        builder.Append("    return \"field\";\n");
        builder.Append("};\n\n");
        builder.Append("var toLoggingScope = (scope: ContractScope | string | null | undefined): LoggingScope => telemetryScopeMapping[normalizeContractScope(scope)];\n\n");


        builder.Append($"var telemetryStudyValidationDiagnosis: StudyDiagnosisCode = \"{TelemetryStudyDiagnosisCodes.Validation}\";\n");
        builder.Append($"var telemetryStudyNavigationDiagnosis: StudyDiagnosisCode = \"{TelemetryStudyDiagnosisCodes.Navigation}\";\n\n");



        builder.Append("var telemetryStudyErrorRouting: Record<string, StudyErrorRoute> = {\n");
        var routingPairs = TelemetryStudyErrorRouting.ByErrorCode
            .OrderBy(pair => pair.Key, StringComparer.Ordinal)
            .ToArray();
        for (var index = 0; index < routingPairs.Length; index++)
        {
            var terminator = index == routingPairs.Length - 1 ? "" : ",";
            builder.Append($"    \"{routingPairs[index].Key}\": \"{routingPairs[index].Value.ToString().ToLowerInvariant()}\"{terminator}\n");
        }

        builder.Append("};\n\n");
        builder.Append("var telemetryStudyErrorRoute = (errorCode: string): StudyErrorRoute =>\n");
        builder.Append("    telemetryStudyErrorRouting[errorCode] ?? \"validation\";\n\n");

        builder.Append($"var telemetryUnknownParticipantId = \"{TelemetryEnvelopeContextDefaults.UnknownParticipantId}\";\n");
        builder.Append($"var telemetryUnknownTaskId = \"{TelemetryEnvelopeContextDefaults.UnknownTaskId}\";\n");


        builder.Append($"var telemetryUnidentifiedObject = \"{TelemetryPayloadPlaceholders.UnidentifiedObject}\";\n");

        return builder.ToString();
    }

    private static IEnumerable<string> Sorted(IEnumerable<string> values)
        => values.OrderBy(value => value, StringComparer.Ordinal);

    private static void AppendRuntimeSet(
        StringBuilder builder,
        string variableName,
        string typeName,
        IEnumerable<string> values)
    {
        builder.Append($"var {variableName}: ReadonlySet<{typeName}> = new Set([\n");
        var valueList = values.ToArray();
        for (var index = 0; index < valueList.Length; index++)
        {
            var terminator = index == valueList.Length - 1 ? "" : ",";
            builder.Append($"    \"{valueList[index]}\"{terminator}\n");
        }

        builder.Append("]);\n\n");
    }
}
